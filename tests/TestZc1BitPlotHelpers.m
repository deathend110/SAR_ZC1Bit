classdef TestZc1BitPlotHelpers < matlab.unittest.TestCase
    % 绘图脚本的轻量辅助逻辑测试：RT 种子、B0 中位样本、最优单元、校准 Δ。

    methods (TestClassSetup)
        function addRepoPaths(t)
            repo = string(fileparts(fileparts(mfilename("fullpath"))));
            t.applyFixture(matlab.unittest.fixtures.PathFixture(repo));
            t.applyFixture(matlab.unittest.fixtures.PathFixture(fullfile(repo, "scripts")));
            t.applyFixture(matlab.unittest.fixtures.PathFixture(fullfile(repo, "src", "workflow")));
        end
    end

    methods (Test)
        function stage2RtSeedIsStableAndDocumented(t)
            t.verifyEqual(zc1bit_stage2_rt_seed(2026, ...
                "rb_R1A1_range_rt_as0p6", 1), 173943027);
            t.verifyEqual(zc1bit_stage2_rt_seed(2026, ...
                "rb_R1A1_range_rt_as0p6", 2), 173943028);
            t.verifyEqual(zc1bit_stage2_rt_seed(2026, ...
                "rb_R9A1_range_rsft_sm6_fr1p6_fa0", 2), 189233028);
            t.verifyEqual(zc1bit_stage2_rt_seed(2026, "same_tag", 7), ...
                zc1bit_stage2_rt_seed(2026, "same_tag", 7));
        end

        function medianB0SampleSelection(t)
            detail = table( ...
                [1; 1; 2; 2; 3; 3], ...
                ["B0_par_raw"; "R1_par_raw"; "B0_par_raw"; "R1_par_raw"; ...
                "B0_par_raw"; "R1_par_raw"], ...
                [0.50; 0.10; 0.90; 0.20; 0.70; 0.30], ...
                'VariableNames', {'SampleID', 'VariantKey', 'SSIM'});
            t.verifyEqual(zc1bit_b0_median_sample_id(detail, "B0_par_raw"), 3);
        end

        function bestUnitUsesSsimThenPsnr(t)
            T = table( ...
                ["R1_par_raw"; "R1_par_raw"; "R1_par_raw"], ...
                ["u1"; "u2"; "u3"], ...
                [0.80; 0.80; 0.70], ...
                [30.0; 31.0; 40.0], ...
                'VariableNames', {'VariantKey', 'UnitKey', 'SSIM_Mean', 'PSNR_Mean'});
            row = zc1bit_select_best_unit(T, "R1_par_raw");
            t.verifyEqual(row.UnitKey, "u2");
            t.verifyError(@() zc1bit_select_best_unit(T, "missing"), ...
                "zc1bit:PlotNoVariantRows");
        end

        function calibrationDeltaMatchesBaseline(t)
            S = table( ...
                ["u1"; "u1"; "u2"; "u2"], ...
                ["B0_par_raw"; "R1_par_raw"; "B0_par_raw"; "R1_par_raw"], ...
                ["range_branch"; "range_branch"; "range_branch"; "range_branch"], ...
                ["RSFT"; "RSFT"; "RSFT"; "RSFT"], ...
                [1; 1; 2; 2], ...
                [0.60; 0.65; 0.70; 0.68], ...
                [20.0; 21.0; 22.0; 21.5], ...
                'VariableNames', {'UnitKey', 'VariantKey', 'Branch', ...
                'ThresholdType', 'Q', 'Calibration_SSIM_Mean', 'Calibration_PSNR_Mean'});
            T = zc1bit_build_calibration_delta(S, "B0_par_raw");
            t.verifyEqual(height(T), 2);
            t.verifyEqual(T.DeltaSSIM_Mean, [0.05; -0.02], "AbsTol", 1e-12);
            t.verifyEqual(T.DeltaPSNR_Mean, [1.0; -0.5], "AbsTol", 1e-12);
        end

        function plotStyleHasRequiredFields(t)
            style = zc1bit_plot_style();
            required = ["font_name", "font_size", "line_width", "baseline_color", ...
                "pseudo_colors", "export_resolution"];
            t.verifyTrue(all(isfield(style, cellstr(required))));
        end
    end
end
